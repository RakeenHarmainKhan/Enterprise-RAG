class LangfuseTracer:
    """Own an explicitly enabled SDK client without capturing application content."""

    def __init__(self, yaml_cfg: YamlAppConfig, settings: Settings) -> None:
        """Validate credentials only when both tracing flags are enabled."""
        self._client: Langfuse | None = None
        if not (yaml_cfg.observability.langfuse_enabled and yaml_cfg.observability.tracing):
            return
        if not settings.langfuse_secret_key or not settings.langfuse_public_key:
            raise ValueError("Enabled tracing requires LANGFUSE_PUBLIC_KEY and LANGFUSE_SECRET_KEY")
        self._client = Langfuse(
            secret_key=settings.langfuse_secret_key,
            public_key=settings.langfuse_public_key,
            base_url=settings.langfuse_base_url,
            tracing_enabled=True,
        )

    @property
    def enabled(self) -> bool:
        """Report whether a tracing client was configured, not remote readiness."""
        return self._client is not None

    @property
    def client(self) -> Langfuse | None:
        """Expose the SDK client for explicitly approved integrations."""
        return self._client

    @contextmanager
    def span(self, name: str, metadata: Metadata | None = None) -> Iterator[Metadata]:
        """Record timings and safe metadata; never send exception messages or stacks."""
        values = dict(metadata or {})
        if self._client is None:
            yield values
            return
        manager = None
        observation = None
        try:
            manager = self._client.start_as_current_observation(name=name, as_type="span")
            observation = manager.__enter__()
        except (HTTPError, OSError, RuntimeError, ValueError) as error:
            log.warning("tracing_start_failed", operation=name, error_type=type(error).__name__)
            manager = None
        try:
            yield values
        except BaseException as error:
            values.update(outcome="error", error_type=type(error).__name__)
            raise
        finally:
            if observation is not None:
                values.setdefault("outcome", "success")
                try:
                    observation.update(
                        metadata=values,
                        level="ERROR" if values["outcome"] == "error" else "DEFAULT",
                    )
                except (HTTPError, OSError, RuntimeError, ValueError) as error:
                    log.warning("tracing_update_failed", operation=name, error_type=type(error).__name__)
            if manager is not None:
                try:
                    # Do not let the SDK automatically serialize application exceptions.
                    manager.__exit__(None, None, None)
                except (HTTPError, OSError, RuntimeError, ValueError) as error:
                    log.warning("tracing_end_failed", operation=name, error_type=type(error).__name__)

    def flush(self) -> None:
        """Flush queued telemetry, logging transport failures without changing app results."""
        if self._client is not None:
            try:
                self._client.flush()
            except (HTTPError, OSError, RuntimeError, ValueError) as error:
                log.warning("tracing_flush_failed", error_type=type(error).__name__)

    def shutdown(self) -> None:
        """Flush telemetry and release SDK background resources on application shutdown."""
        if self._client is not None:
            try:
                self._client.shutdown()
            except (HTTPError, OSError, RuntimeError, ValueError) as error:
                log.warning("tracing_shutdown_failed", error_type=type(error).__name__)


_tracer_var: contextvars.ContextVar[LangfuseTracer | None] = contextvars.ContextVar(
    "langfuse_tracer", default=None
)


def set_current_tracer(tracer: LangfuseTracer | None) -> contextvars.Token[LangfuseTracer | None]:
    """Bind tracing to the current request or explicitly scoped background operation."""
    return _tracer_var.set(tracer)


def reset_current_tracer(token: contextvars.Token[LangfuseTracer | None]) -> None:
    """Restore the previous tracing context."""
    _tracer_var.reset(token)


def get_current_tracer() -> LangfuseTracer | None:
    """Read the tracer in the current execution context."""
    return _tracer_var.get()


@contextmanager
def trace_stage(name: str, **metadata: str | float | bool) -> Iterator[Metadata]:
    """Record a pipeline stage without recording arguments, results or raw text."""
    tracer = get_current_tracer()
    if tracer is None:
        yield dict(metadata)
    else:
        with tracer.span(name, metadata) as values:
            yield values


def trace_span(name: str | None = None) -> Callable[[Callable[P, R]], Callable[P, R]]:
    """Instrument synchronous and asynchronous helpers without capturing their payloads."""
    def decorator(fn: Callable[P, R]) -> Callable[P, R]:
        """Wrap a helper while preserving its signature and exception behavior."""
        span_name = name or fn.__name__

        @functools.wraps(fn)
        async def async_wrapper(*args: P.args, **kwargs: P.kwargs):
            """Keep the stage active across an awaited operation."""
            async_fn = cast(Callable[P, Awaitable[object]], fn)
            with trace_stage(span_name):
                return await async_fn(*args, **kwargs)

        @functools.wraps(fn)
        def sync_wrapper(*args: P.args, **kwargs: P.kwargs):
            """Keep the stage active for a synchronous operation, including worker threads."""
            with trace_stage(span_name):
                return fn(*args, **kwargs)

        return cast(Callable[P, R], async_wrapper if inspect.iscoroutinefunction(fn) else sync_wrapper)

    return decorator


class TracingMiddleware:
    """Bind the application tracer across an entire HTTP response, including SSE."""

    def __init__(self, app: ASGIApp) -> None:
        """Keep the middleware independent of application lifespan context propagation."""
        self.app = app

    async def __call__(self, scope: Scope, receive: Receive, send: Send) -> None:
        """Trace only known RAG operations, without URLs, headers, bodies or identifiers."""
        names = {
            "/query": "rag.query",
            "/query/batch": "rag.batch",
            "/documents/upload": "rag.ingestion",
        }
        name = names.get(scope.get("path", ""))
        state = getattr(scope.get("app"), "state", None)
        tracer = getattr(getattr(state, "app_state", None), "langfuse", None)
        if scope["type"] != "http" or scope.get("method") != "POST" or name is None or tracer is None:
            await self.app(scope, receive, send)
            return
        token = set_current_tracer(tracer)
        try:
            with tracer.span(name) as metadata:
                async def traced_send(message: Message) -> None:
                    """Capture response status without reading response content."""
                    if message["type"] == "http.response.start":
                        status = message["status"]
                        metadata["http_status"] = status
                        metadata["outcome"] = "error" if status >= 500 else "rejected" if status >= 400 else "success"
                    await send(message)

                await self.app(scope, receive, traced_send)
        finally:
            reset_current_tracer(token)
