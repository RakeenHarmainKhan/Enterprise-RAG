"""Retrieval orchestration: route → multi-strategy search → fuse → rerank."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from opensearchpy import OpenSearch

from app.core.config import RetrievalConfig, YamlAppConfig
from app.core.llm import LLMProvider
from app.ingestion.embedders import EmbedderPlugin
from app.observability.langfuse_tracer import trace_span, trace_stage
from app.retrieval.fusion import build_fusion
from app.retrieval.rerankers import build_reranker
from app.retrieval.router import build_router
from app.retrieval.strategies import StrategyHit, build_retriever, select_strategies


@dataclass
class RetrievedChunk:
    chunk_id: str
    document_id: str
    text: str
    score: float
    metadata: dict[str, Any] = field(default_factory=dict)
    strategy: str = ""

    @staticmethod
    def from_hit(h: StrategyHit) -> RetrievedChunk:
        return RetrievedChunk(
            chunk_id=h.chunk_id,
            document_id=h.document_id,
            text=h.text,
            score=h.score,
            metadata=dict(h.metadata),
            strategy=h.strategy,
        )


class RetrievalEngine:
    def __init__(
        self,
        yaml_cfg: YamlAppConfig,
        opensearch: OpenSearch,
        embedder: EmbedderPlugin,
        llm: LLMProvider | None,
    ) -> None:
        self._cfg: RetrievalConfig = yaml_cfg.retrieval
        self._os = opensearch
        self._embedder = embedder
        self._llm = llm
        index_name = str(yaml_cfg.ingestion.indexer_params.get("index_name", "enterprise_rag_chunks"))
        self._index_name = index_name
        self._router = build_router(self._cfg.router, llm=llm)
        self._fusion = build_fusion(self._cfg.fusion, **self._cfg.fusion_params)
        self._reranker = build_reranker(self._cfg.reranker, **self._cfg.reranker_params)

    def _strategy_specs(self) -> list[tuple[str, float, dict[str, Any]]]:
        out: list[tuple[str, float, dict[str, Any]]] = []
        for item in self._cfg.strategies:
            out.append((item.name, float(item.weight), dict(item.params)))
        if not out:
            out = [
                ("dense", 0.5, {"k": 20}),
                ("sparse", 0.5, {"k": 20}),
            ]
        return out

    # Generated by GitHub Copilot - Nov-11-2026
    @trace_span("retrieval")
    async def retrieve(
        self,
        query: str,
        *,
        collection_id: str | None = None,
        top_k: int | None = None,
    ) -> list[RetrievedChunk]:
        with trace_stage("query_embedding"):
            embedding = self._embedder.embed(query)
        decision = await self._router.route(query)
        specs = select_strategies(decision, self._strategy_specs())

        lists: list[list[StrategyHit]] = []
        weights: list[float] = []
        for name, weight, params in specs:
            # Generated by GitHub Copilot - Nov-01-2026
            params = dict(params)
            k = int(params.pop("k", 20))
            retriever = build_retriever(name, self._os, self._index_name)
            try:
                hits = retriever.search(
                    query,
                    embedding,
                    k,
                    collection_id,
                    **params,
                )
            except Exception:
                if name == "hybrid_strategy" or name == "hybrid":
                    dense = build_retriever("dense", self._os, self._index_name)
                    sparse = build_retriever("sparse", self._os, self._index_name)
                    h1 = dense.search(query, embedding, k, collection_id, **params)
                    h2 = sparse.search(query, None, k, collection_id, **params)
                    hits = h1 + h2
                else:
                    raise
            lists.append(hits)
            weights.append(weight)

        fused = self._fusion.fuse(lists, weights, **self._cfg.fusion_params)
        # Generated by GitHub Copilot - Nov-01-2026
        reranker_params = dict(self._cfg.reranker_params)
        rk = int(reranker_params.pop("top_k", top_k or 8))
        # Generated by GitHub Copilot - Nov-11-2026
        with trace_stage("reranking", candidates=len(fused), top_k=rk) as metadata:
            reranked = self._reranker.rerank(query, fused, rk, **reranker_params)
            metadata["returned_chunks"] = len(reranked)
        return [RetrievedChunk.from_hit(h) for h in reranked]
